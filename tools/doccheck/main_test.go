package main

import (
	"bytes"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// writeTree creates files under a temporary directory and returns it.
func writeTree(t *testing.T, files map[string]string) string {
	t.Helper()
	root := t.TempDir()
	for name, body := range files {
		path := filepath.Join(root, name)
		if err := os.MkdirAll(filepath.Dir(path), 0o750); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(body), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	return root
}

func TestRun(t *testing.T) {
	t.Parallel()
	tests := []struct {
		name     string
		files    map[string]string
		arg      string
		wantCode int
		want     []string // substrings of stdout
		dontWant []string
	}{
		{
			name: "all documented",
			files: map[string]string{
				"a.go": "// Package a does things.\npackage a\n\n// F does a thing.\nfunc F() {}\n",
			},
			arg:      "/...",
			wantCode: 0,
		},
		{
			name: "missing function and method comments",
			files: map[string]string{
				"a.go": "// Package a does things.\npackage a\n\ntype T struct{}\ntype G[K any] struct{}\ntype H[K, V any] struct{}\n\nfunc F() {}\nfunc (t *T) M() {}\nfunc (G[K]) N() {}\nfunc (H[K, V]) O() {}\n",
			},
			arg:      "/...",
			wantCode: 1,
			want:     []string{"F has no doc comment", "T.M has no doc comment", "G.N has no doc comment", "H.O has no doc comment", "4 missing"},
		},
		{
			name: "missing package comment",
			files: map[string]string{
				"a.go": "package a\n\n// F does a thing.\nfunc F() {}\n",
				"b.go": "package a\n",
			},
			arg:      "",
			wantCode: 1,
			want:     []string{"package a has no package comment"},
		},
		{
			name: "package comment in any file is enough",
			files: map[string]string{
				"a.go":   "package a\n",
				"doc.go": "// Package a does things.\npackage a\n",
			},
			arg:      "",
			wantCode: 0,
		},
		{
			name: "tests, generated files and skipped directories are ignored",
			files: map[string]string{
				"a.go":               "// Package a does things.\npackage a\n",
				"a_test.go":          "package a\n\nfunc helper() {}\n",
				"gen.go":             "// Code generated by hand. DO NOT EDIT.\n\npackage a\n\nfunc G() {}\n",
				"testdata/x.go":      "package x\n\nfunc X() {}\n",
				".hidden/y.go":       "package y\n\nfunc Y() {}\n",
				"_skip/z.go":         "package z\n\nfunc Z() {}\n",
				"vendor/v/v.go":      "package v\n\nfunc V() {}\n",
				"sub/doc.go":         "// Package sub is nested.\npackage sub\n",
				"sub/notes.txt":      "not go",
				"sub/deeper/main.go": "// Command deeper runs.\npackage main\n\n// main runs.\nfunc main() {}\n",
			},
			arg:      "/...",
			wantCode: 0,
		},
		{
			name: "non-recursive argument ignores subdirectories",
			files: map[string]string{
				"a.go":     "// Package a does things.\npackage a\n",
				"sub/b.go": "package b\n\nfunc B() {}\n",
			},
			arg:      "",
			wantCode: 0,
		},
		{
			name: "recursive argument checks subdirectories",
			files: map[string]string{
				"a.go":     "// Package a does things.\npackage a\n",
				"sub/b.go": "package b\n\nfunc B() {}\n",
			},
			arg:      "/...",
			wantCode: 1,
			want:     []string{"B has no doc comment", "package b has no package comment"},
			dontWant: []string{"package a"},
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()
			root := writeTree(t, tt.files)
			var stdout, stderr bytes.Buffer
			code := run([]string{root + tt.arg}, &stdout, &stderr)
			if code != tt.wantCode {
				t.Fatalf("exit code %d, want %d\nstdout:\n%s\nstderr:\n%s", code, tt.wantCode, stdout.String(), stderr.String())
			}
			for _, w := range tt.want {
				if !strings.Contains(stdout.String(), w) {
					t.Errorf("stdout missing %q:\n%s", w, stdout.String())
				}
			}
			for _, w := range tt.dontWant {
				if strings.Contains(stdout.String(), w) {
					t.Errorf("stdout has %q:\n%s", w, stdout.String())
				}
			}
		})
	}
}

func TestRunErrors(t *testing.T) {
	t.Parallel()
	root := writeTree(t, map[string]string{
		"file.txt": "x",
		"bad/a.go": "package",
	})
	tests := []struct {
		name string
		arg  string
	}{
		{"missing directory", filepath.Join(root, "nope")},
		{"not a directory", filepath.Join(root, "file.txt")},
		{"parse error", filepath.Join(root, "bad")},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()
			var stdout, stderr bytes.Buffer
			if code := run([]string{tt.arg}, &stdout, &stderr); code != 2 {
				t.Fatalf("exit code %d, want 2", code)
			}
			if !strings.HasPrefix(stderr.String(), "doccheck: ") {
				t.Errorf("stderr = %q", stderr.String())
			}
		})
	}
}

func TestRunDefaultsToCurrentDir(t *testing.T) {
	// Not parallel: changes the working directory.
	root := writeTree(t, map[string]string{"a.go": "package a\n"})
	t.Chdir(root)
	for _, args := range [][]string{nil, {"./..."}, {"..."}} {
		var stdout, stderr bytes.Buffer
		if code := run(args, &stdout, &stderr); code != 1 || !strings.Contains(stdout.String(), "package a has no package comment") {
			t.Errorf("run(%q) = %d, stdout %q", args, code, stdout.String())
		}
	}
}
